import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Regenerates `src/utils/html-entity-table.generated.ts` from the WHATWG named character reference list.
 *
 * @remarks Run with `node --import tsx ./scripts/generate-html-entity-table.ts`. The list is frozen by the
 * HTML spec, so this only needs to run if the encoding below changes.
 */

const SOURCE = 'https://html.spec.whatwg.org/entities.json';
const outputPath = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	'../src/utils/html-entity-table.generated.ts',
);

type EntityList = Record<string, { codepoints: number[] }>;

const entities = (await (await fetch(SOURCE)).json()) as EntityList;
const named = Object.entries(entities)
	.filter(([key]) => key.endsWith(';'))
	.map(([key, { codepoints }]) => [key.slice(1, -1), codepoints] as const)
	.sort(([a], [b]) => (a < b ? -1 : 1));
const legacy = Object.keys(entities)
	.filter((key) => !key.endsWith(';'))
	.map((key) => key.slice(1));

for (const name of legacy) {
	if (entities[`&${name}`]?.codepoints.join() !== entities[`&${name};`]?.codepoints.join()) {
		throw new Error(`Legacy reference &${name} differs from &${name};`);
	}
}

let previous = '';
const entries = named.map(([name, codepoints]) => {
	let shared = 0;
	while (shared < Math.min(name.length, previous.length, 35) && name[shared] === previous[shared]) shared += 1;
	previous = name;
	return `${shared.toString(36)}${name.slice(shared)}:${codepoints.map((codepoint) => codepoint.toString(36)).join('.')}`;
});

writeFileSync(
	outputPath,
	`// Generated by scripts/generate-html-entity-table.ts from ${SOURCE}. Do not edit.

/**
 * Named character references, sorted and front-coded. Entries are joined by \`;\`; each is one base-36 digit
 * (characters shared with the previous name), the rest of the name, \`:\`, then base-36 code points joined by \`.\`.
 */
export const NAMED_ENTITY_DATA =
	'${entries.join(';')}';

/** Names the spec also decodes without a trailing semicolon. */
export const LEGACY_ENTITY_NAMES = '${legacy.join(' ')}';
`,
);
